// Signal weight used by the "Best deals first" sort: a big % off an inflated
// list price is worth less than a smaller % off a real low.
export const SIGNAL_WEIGHT = { "New low": 1.0, "Strong price": 0.9, "Routine sale": 0.6, "Inflated": 0.3 };

export function discountPct(d) {
  return Math.round(((d.usual - d.sale) / d.usual) * 100);
}

export function savedAmount(d) {
  return d.usual - d.sale;
}

export function dealScore(d) {
  return discountPct(d) * (SIGNAL_WEIGHT[d.signal] ?? 0.5);
}

export function fmtUsd(n) {
  return "$" + n.toFixed(2).replace(/\.00$/, "");
}
